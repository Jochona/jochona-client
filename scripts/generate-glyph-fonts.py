HEX_RE = re.compile(r"^([a-z0-9_]+):\s*U\+([0-9A-Fa-f]{4,6})\s*$")

QML_HEAD = """// Jochona controller glyph system (M1). Generated by
// scripts/generate-glyph-fonts.py from assets/vendor/kenney-input-prompts-1.5.zip
// (CC0, Kenney Input Prompts 1.5). DO NOT EDIT BY HAND - edit the generator.
//
// Glyphs ship as per-family icon FONTS, so a glyph is just a Text: it inherits
// the theme color and scales with the type ramp. Logical names are unified on
// Xbox vocabulary; PlayStation/Switch/Steam sources land on the same buttons.
//
//   Text {
//       text: Glyphs.glyph(Glyphs.family, "a")
//       font.family: Glyphs.fontFamily(Glyphs.family)
//       color: Tokens.textPrimary
//   }
//
// family: "xbox" | "playstation" | "nintendo" | "steam" | "generic"
// Unknown families resolve to "generic"; "auto" follows the detected pad (M2).
pragma Singleton
import QtQuick 2.0

QtObject {
    id: root

    // Default prompt family until the M2 controller manager reports identity;
    // writable so the UI can bind it to the connected controller's family.
    property string family: "xbox"

    readonly property var fontFiles: {FONTS}

    property var _loaders: ({})

    Component.onCompleted: {
        var loaders = ({})
        var names = Object.keys(fontFiles)
        for (var i = 0; i < names.length; i++) {
            loaders[names[i]] = fontLoaderComp.createObject(root, {
                "source": "qrc:/fonts/" + fontFiles[names[i]] + ".ttf"
            })
        }
        root._loaders = loaders
    }

    // QtObject has no default property — the Component must hang off an
    // explicit property or instantiation of the singleton fails at runtime.
    readonly property Component fontLoaderComp: Component {
        FontLoader {}
    }

    function fontFamily(family) {
        var key = (family in glyphs) ? family : "generic"
        var loader = root._loaders[key]
        return loader && loader.name.length > 0 ? loader.name : "Inter"
    }

    // Returns the glyph character, or "" for unknown names/families.
    function glyph(family, logical) {
        var key = (family in glyphs) ? family : "generic"
        var ch = glyphs[key][logical]
        if (ch === undefined) {
            ch = glyphs["generic"][logical]
        }
        return ch === undefined ? "" : ch
    }

    // logical name -> character, per family (generated; unified vocabulary)
    readonly property var glyphs: {
{GLYPHS}
    }
}
"""


def load_map(zf: zipfile.ZipFile, folder: str) -> dict:
    base = FAMILIES[folder][1]
    name = f"{folder}/Fonts/{base}_map.txt"
    out = {}
    for line in zf.read(name).decode("utf-8").splitlines():
        m = HEX_RE.match(line.strip())
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def main() -> None:
    zf = zipfile.ZipFile(ZIP)
    FONTS_DIR.mkdir(exist_ok=True)

    fonts = {}
    maps = {}
    for folder, (key, base) in FAMILIES.items():
        data = zf.read(f"{folder}/Fonts/{base}.ttf")
        (FONTS_DIR / f"{base}.ttf").write_bytes(data)
        print(f"wrote app/fonts/{base}.ttf ({len(data)} bytes)")
        fonts[key] = base
        maps[key] = load_map(zf, folder)

    generic = maps["generic"]
    blocks = []
    missing = []
    for key in ["xbox", "playstation", "nintendo", "steam", "generic"]:
        fam = maps[key]
        entries = []
        for logical, per_family in LOGICAL.items():
            src = per_family.get(key)
            cp = fam.get(src) if src else None
            if cp is None and src:
                missing.append(f"{key}.{logical} (source '{src}' not in family map)")
                cp = generic.get(src)  # generic names often shared across families
            if cp is None:
                continue
            entries.append(f'            "{logical}": "\\u{{{cp:X}}}"')
        blocks.append(f'        "{key}": {{\n' + ",\n".join(entries) + "\n        }")

    fonts_block = ",\n              ".join(f'"{k}": "{v}"' for k, v in fonts.items())
    qml = QML_HEAD.replace("{FONTS}", "{\n              " + fonts_block + "\n          }")
    qml = qml.replace("{GLYPHS}", ",\n".join(blocks))
    OUT_QML.write_text(qml, encoding="utf-8")
    print(f"wrote app/gui/style/Glyphs.qml "
          f"({len(LOGICAL)} logical glyphs x {len(FAMILIES)} families)")
    for m in missing:
        print(f"note: {m}")


if __name__ == "__main__":
    main()
