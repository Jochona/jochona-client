#!/usr/bin/env python3
"""Generate the controller glyph system from the vendored Kenney Input Prompts pack.

Inputs (tracked):  assets/vendor/kenney-input-prompts-1.5.zip  (CC0)
Outputs (tracked): app/fonts/kenney_input_*.ttf                (per-family glyph fonts)
                   app/gui/style/Glyphs.qml                    (logical-name singleton)

Glyph FONTS (not sprites) are the delivery format: a glyph Text inherits the
active theme color and scales with the type ramp for free. Logical names are
unified across families on Xbox vocabulary; PlayStation's
cross/circle/square/triangle and Switch's A/B/X/Y land on the same logical
buttons. Face-button swap preferences remain a UI concern, not a font one.
"""
